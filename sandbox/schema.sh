#!/usr/bin/env bash
# Dump the Heroku schema, split out the CREATE INDEX statements, and load
# extensions plus the index-free schema into Render.
#
# Output (in $ARTIFACT_DIR/schema/):
#   schema_full.sql        pg_dump --schema-only of $SCHEMAS
#   extensions.sql         CREATE EXTENSION IF NOT EXISTS ... from pg_extension
#   schema_no_indexes.sql  what gets loaded now
#   indexes.sql            CREATE [UNIQUE] INDEX lines, built by build_indexes.sh
#   index_post.sql         statements that need those indexes (ATTACH PARTITION,
#                          COMMENT ON INDEX, CLUSTER ON, ...), run after the build
#   indexes_kept.txt       unique indexes kept in the schema because a foreign
#                          key depends on them
#
# Refuses to run if any target table already contains rows.
set -euo pipefail
# shellcheck source=sandbox/env.sh
. "$(dirname "$0")/env.sh"
ensure_run_user "$@"
ensure_dirs
acquire_lock
require_env HEROKU_DATABASE_URL RENDER_DATABASE_URL
write_service_file

OUT="$ARTIFACT_DIR/schema"
mkdir -p "$OUT"

# ------------------------------------------------------ target must be empty
nonempty=""
target_tables=0
while IFS= read -r t; do
  [ -n "$t" ] || continue
  target_tables=$((target_tables + 1))
  if [ "$(psql_dst -c "SELECT EXISTS (SELECT 1 FROM $t)" </dev/null)" = t ]; then
    nonempty="$nonempty $t"
  fi
done <<EOF
$(list_tables psql_dst)
EOF
if [ -n "$nonempty" ]; then
  die "refusing to load the schema: target tables already contain rows:$nonempty. Run reset_target.sh --confirm first."
fi
if [ "$target_tables" -gt 0 ]; then
  if has_state schema.done; then
    log "schema already loaded at $(state_time schema.done) ($target_tables tables); nothing to do"
    exit 0
  fi
  die "Render already has $target_tables table(s) in $SCHEMAS that schema.sh did not load. Drop them, or run reset_target.sh --drop-schema --confirm."
fi
clear_state schema.done

# ------------------------------------------------------------------- dump
use_client_tools
log "dumping schema of $SCHEMAS from Heroku with pg_dump $PG_CLIENT_MAJOR"
dump_args=()
IFS=',' read -r -a schema_list <<<"$SCHEMAS"
for s in "${schema_list[@]}"; do
  s="$(printf '%s' "$s" | tr -d '[:space:]')"
  [ -n "$s" ] && dump_args+=(-n "$(ident "$s")")
done
"$PG_DUMP" -d "$SRC_SERVICE" --schema-only --no-owner --no-privileges \
  --no-publications --no-subscriptions --no-security-labels --no-tablespaces \
  "${dump_args[@]}" -f "$OUT/schema_full.sql" 2> >(redact >&2) \
  || die "pg_dump failed"

# ------------------------------------------------------------- extensions
{
  echo "-- Generated by schema.sh from Heroku's pg_extension at $(ts)"
  while IFS=$'\t' read -r ext ext_schema; do
    [ -n "$ext" ] && extension_sql "$ext" "$ext_schema"
  done <<EOF
$(psql_src -c "SELECT e.extname, n.nspname FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace WHERE e.extname <> 'plpgsql' ORDER BY 1")
EOF
} >"$OUT/extensions.sql"

# ------------------------------------------- indexes a foreign key needs
# A foreign key must reference a unique index. If that index is a plain
# CREATE UNIQUE INDEX (not a PRIMARY KEY/UNIQUE constraint), it has to stay
# in the schema or the ADD CONSTRAINT ... FOREIGN KEY statement fails.
psql_src -c "
  SELECT DISTINCT quote_ident(n.nspname) || '.' || quote_ident(i.relname)
  FROM pg_constraint fk
  JOIN pg_class i ON i.oid = fk.conindid
  JOIN pg_namespace n ON n.oid = i.relnamespace
  WHERE fk.contype = 'f'
    AND NOT EXISTS (SELECT 1 FROM pg_constraint c
                    WHERE c.conindid = fk.conindid AND c.contype IN ('p','u','x'))
  ORDER BY 1" >"$OUT/indexes_kept.txt"

# ------------------------------------------------------------------ split
perl "$MIGRATE_HOME/split_schema.pl" "$OUT/indexes_kept.txt" "$OUT/indexes.sql" "$OUT/index_post.sql" \
  <"$OUT/schema_full.sql" >"$OUT/schema_no_indexes.sql" \
  || die "splitting the schema dump failed"

n_tables="$(grep -c '^CREATE TABLE ' "$OUT/schema_no_indexes.sql" || true)"
n_indexes="$(grep -c . "$OUT/indexes.sql" || true)"
grep -q '^CREATE \(UNIQUE \)\?INDEX ' "$OUT/schema_no_indexes.sql" \
  && log "kept in schema for foreign keys: $(tr '\n' ' ' <"$OUT/indexes_kept.txt")"

# ------------------------------------------------------------------- load
log "loading extensions into Render"
psql_dst -1 -f "$OUT/extensions.sql" 2>&1 >/dev/null | redact >&2 \
  || die "loading extensions failed (see output above)"
log "loading schema without indexes into Render (single transaction)"
psql_dst -1 -f "$OUT/schema_no_indexes.sql" 2>&1 >/dev/null | redact >&2 \
  || die "loading schema_no_indexes.sql failed; nothing was committed"

mark_state schema.done
log "schema loaded: $n_tables table(s); $n_indexes index(es) deferred to build_indexes.sh"
say "schema: loaded $n_tables tables, deferred $n_indexes indexes (artifacts in $OUT)"
